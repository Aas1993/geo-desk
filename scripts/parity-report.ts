// Regenerates docs/parity.md from the layer registry so the DiploMaps parity list cannot drift from what is actually live.
// Run: npm run parity
import { writeFileSync } from "node:fs";
import { GROUPS, LAYERS, statusLabel } from "../src/lib/layers/registry";

const live = LAYERS.filter((l) => l.status === "live"), soon = LAYERS.filter((l) => l.status === "soon"), key = LAYERS.filter((l) => l.status === "needs-key"), na = LAYERS.filter((l) => l.status === "unavailable");
const members = LAYERS.filter((l) => l.kind === "members"); const nonMember = LAYERS.filter((l) => l.kind !== "members");
const lines: string[] = [];
lines.push("# DiploMaps parity tracker", "", "Generated by `npm run parity` from `src/lib/layers/registry.ts`. Do not edit the layer tables by hand; edit the registry.", "",
  `**Layers:** ${live.length} live · ${soon.length} planned · ${key.length} need a free key · ${na.length} have no compliant source (of ${LAYERS.length}). Membership layers: ${members.filter((l) => l.status === "live").length} of ${members.length} live.`, "");
for (const g of GROUPS) {
  const ls = nonMember.filter((l) => l.group === g.id); if (!ls.length) continue;
  lines.push(`## ${g.en}`, "", "| Layer | Status | Note |", "|---|---|---|", ...ls.map((l) => `| ${l.en} | ${statusLabel[l.status].en} | ${(l.note ?? "").replace(/\|/g, "/")} |`), "");
}
lines.push("## Membership layers", "", `Live: ${members.filter((l) => l.status === "live").map((l) => l.en.split(" · ")[0]).join(", ")}.`, "", `Planned (no trustworthy member list yet): ${members.filter((l) => l.status !== "live").map((l) => l.en.split(" · ")[0]).join(", ")}.`, "");
lines.push("## Not layers", "", "| Feature | Status | Where / what is missing |", "|---|---|---|",
  ...[
    ["Country dossier (overview, economy, trade, military, UN votes, society, news)", "Live", "Country panel"],
    ["Compare two countries", "Live", "Compare view"],
    ["Bilateral trade with the UAE (UN Comtrade)", "Live", "Trade tab"],
    ["**UAE agreements, CEPAs, tax and air treaties, joint committees, economic offices**", "Live", "Agreements tab + 5 layers (MOFA, Ministry of Foreign Trade)"],
    ["**Direct flights from the UAE per country (active vs suspended)**", "Live", "Agreements tab + layer (Wikipedia/Wikidata)"],
    ["**UAE investment abroad per country**", "Live", "Agreements tab + layer (IMF); no public count of UAE companies exists"],
    ["Memberships card per country", "Live", "Overview tab"],
    ["Alerts bell and feed (UAE radar, everywhere, flagged, security)", "Live", "Top bar"],
    ["AI country brief with citations and cost guardrails", "Live", "AI brief tab"],
    ["Day/night, flat/globe, satellite basemap, my location, time window, URL-shared state", "Live", "Right rail, layers drawer"],
    ["Arabic/English with RTL, light/dark, text size", "Live", "Top bar, right rail"],
    ["UAE markets desk (ADX/DFM) with AI research notes", "Live", "Markets (beyond DiploMaps)"],
    ["Customizable dashboard with role presets and widgets", "Not built", "Next: widget grid on existing data"],
    ["Watchlist of countries", "Not built", "Next with the dashboard"],
    ["One-page country export", "Partial", "AI brief copies/downloads Markdown; print route not built"],
    ["Ask (natural-language search) and AI alert triage", "Not built", "Agreed with cost guardrails; not started"],
    ["Guided tour / coach marks", "Partial", "Onboarding card exists; no tour"],
    ["Mobile bottom-nav parity (Map / Layers / Brief / Ask / Share)", "Partial", "Map, Markets, Layers, Share exist"],
  ].map((r) => `| ${r[0]} | ${r[1]} | ${r[2]} |`), "");
writeFileSync(new URL("../docs/parity.md", import.meta.url), lines.join("\n"));
console.log(`docs/parity.md written: ${live.length} live / ${LAYERS.length} layers`);
